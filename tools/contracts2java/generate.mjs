#!/usr/bin/env node
// Generates Java constants from the TypeScript contract in packages/shared (the source of truth
// shared with the web client):
//   permissions.ts -> kernel/security/Permissions.java  (constants, ALL, MANAGER)
//   events.ts      -> shared/events/DomainEvents.java    (event name constants)
// Requires Node >= 22.18 (built-in TypeScript type stripping). Run: node tools/contracts2java/generate.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const src = path.join(root, 'packages/shared/src');
const javaBase = path.join(root, 'backend/src/main/java/com/inventoryerp');
const HEADER = '// @generated by tools/contracts2java from packages/shared — do not edit; change the TS source and re-run.';

async function load(file) {
  // packages/shared is CommonJS; copy to .mts so Node treats it as an ES module with types stripped.
  const tmp = path.join(os.tmpdir(), `contracts2java-${path.basename(file, '.ts')}-${process.pid}.mts`);
  fs.copyFileSync(path.join(src, file), tmp);
  try {
    return await import(pathToFileURL(tmp).href);
  } finally {
    fs.rmSync(tmp, { force: true });
  }
}

const constName = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').replace(/^_|_$/g, '').toUpperCase();
const q = (s) => JSON.stringify(s);

// ---- permissions ----
const perms = await load('permissions.ts');
const entries = [];
(function walk(node, prefix) {
  for (const [key, value] of Object.entries(node)) {
    const name = prefix ? `${prefix}__${constName(key)}` : constName(key);
    if (typeof value === 'string') entries.push([name, value]);
    else walk(value, name);
  }
})(perms.PERMISSIONS, '');
const seen = new Set();
for (const [n] of entries) {
  if (seen.has(n)) throw new Error(`duplicate permission constant ${n}`);
  seen.add(n);
}
const permJava = `${HEADER}
package com.inventoryerp.kernel.security;

import java.util.List;

/**
 * RBAC permission catalog, format {@code resource:action}. Mirrors packages/shared/src/permissions.ts
 * exactly (${perms.ALL_PERMISSIONS.length} permissions). Constant name = GROUP__ACTION.
 */
public final class Permissions {

    private Permissions() {}

${entries.map(([n, v]) => `    public static final String ${n} = ${q(v)};`).join('\n')}

    /** Every permission (Administrator role). */
    public static final List<String> ALL = List.of(
${[...new Set(perms.ALL_PERMISSIONS)].map((p) => `            ${q(p)}`).join(',\n')});

    /** Operational manager role (cash management, no system administration). */
    public static final List<String> MANAGER = List.of(
${perms.MANAGER_PERMISSIONS.map((p) => `            ${q(p)}`).join(',\n')});
}
`;
fs.mkdirSync(path.join(javaBase, 'kernel/security'), { recursive: true });
fs.writeFileSync(path.join(javaBase, 'kernel/security/Permissions.java'), permJava);

// ---- events ----
const events = await load('events.ts');
const evJava = `${HEADER}
package com.inventoryerp.shared.events;

/** Domain event names. Mirrors packages/shared/src/events.ts (EVENTS). */
public final class DomainEvents {

    private DomainEvents() {}

${Object.entries(events.EVENTS).map(([k, v]) => `    public static final String ${constName(k)} = ${q(v)};`).join('\n')}
}
`;
fs.mkdirSync(path.join(javaBase, 'shared/events'), { recursive: true });
fs.writeFileSync(path.join(javaBase, 'shared/events/DomainEvents.java'), evJava);

console.log(`permissions: ${entries.length} constants (${perms.ALL_PERMISSIONS.length} distinct), manager: ${perms.MANAGER_PERMISSIONS.length}, events: ${Object.keys(events.EVENTS).length}`);
