#!/usr/bin/env node
// Generates JPA entities, enums (+ converters) and Spring Data repositories from
// reference/nest-api/prisma/schema.prisma into backend/src/main/java/com/inventoryerp/<module>/domain.
//
// Rules (see docs/DATABASE.md):
//  - Table/column names are the Prisma names verbatim (quoted, case-sensitive).
//  - Only same-module relations become @ManyToOne navigations (read-only join columns);
//    cross-module references stay plain String FK ids (aggregate-by-id).
//  - Enums carry the exact DB/JSON value; persisted via auto-applied AttributeConverter.
//  - @DynamicInsert lets Postgres column defaults apply to null fields.
//  - Re-run is idempotent. Files keep the "@generated" marker line while generator-owned;
//    delete that line to take ownership of a file and the generator will skip it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const schema = fs.readFileSync(path.join(root, 'reference/nest-api/prisma/schema.prisma'), 'utf8');
const outBase = path.join(root, 'backend/src/main/java/com/inventoryerp');
const BASE_PKG = 'com.inventoryerp';
const MARK = '// @generated by tools/prisma2jpa — delete this line to take ownership of the file.';

const JAVA_KW = new Set(
  (
    'abstract assert boolean break byte case catch char class const continue default do double else enum ' +
    'extends final finally float for goto if implements import instanceof int interface long native new ' +
    'package private protected public return short static strictfp super switch synchronized this throw ' +
    'throws transient try void volatile while true false null var record yield sealed permits'
  ).split(' '),
);
const OPTIMISTIC_LOCK = new Set(['Order', 'Invoice', 'PurchaseOrder']);

// ---------- tenancy (port of reference/nest-api/src/kernel/prisma/tenancy.extension.ts) ----------
// ORG_SCOPED models get the Hibernate "tenant" filter, SOFT_DELETE models the "softDelete" filter
// (both enabled per transaction by kernel.tenancy.TenantAwareTransactionManager).
const tenancySrc = fs.readFileSync(path.join(root, 'reference/nest-api/src/kernel/prisma/tenancy.extension.ts'), 'utf8');
function tenancySet(name) {
  const start = tenancySrc.indexOf(`const ${name} = new Set<string>([`);
  if (start < 0) throw new Error(`${name} not found in tenancy.extension.ts`);
  const body = tenancySrc.slice(start, tenancySrc.indexOf(']);', start));
  return new Set([...body.replace(/\/\/.*$/gm, '').matchAll(/'([A-Za-z]+)'/g)].map((m) => m[1]));
}
export const ORG_SCOPED = tenancySet('ORG_SCOPED');
export const SOFT_DELETE = tenancySet('SOFT_DELETE');

// ---------- model -> module ownership ----------
const KERNEL = new Set(['Organization', 'Permission', 'User', 'Role', 'RefreshToken', 'IdempotencyRecord', 'AuditLog', 'LoginAttempt', 'Setting', 'EventOutbox', 'DomainEventLog', 'Notification', 'NotificationPreference', 'PushSubscription', 'File', 'OneTimeToken', 'ApprovalRequest', 'ApprovalDecision', 'ApprovalPolicy', 'ApprovalWorkflow', 'ApprovalStep', 'RecurringDocument', 'RecurringDocumentRun', 'WebhookEndpoint', 'WebhookDelivery', 'FeatureFlag', 'SavedReport', 'SavedReportRun', 'OrganizationModule', 'LifecycleEvent']);
const ACCOUNTING = new Set(['AccountCategory', 'Account', 'Journal', 'JournalEntry', 'JournalLine', 'AccountMapping', 'BankAccount', 'FxRevaluation', 'BankStatementLine', 'BankReconciliationRun', 'CashRegister', 'CashSession', 'CashMovement', 'PosPaymentMethod', 'TenderSettlement', 'CostCenter', 'Currency', 'CurrencyRate']);
const INVOICING = new Set(['Invoice', 'InvoiceItem', 'InvoiceItemModifier', 'InvoiceItemRecipeIngredient', 'Receipt', 'ReceiptItem', 'Payment', 'PaymentAllocation']);
const POS = new Set(['PosHold', 'PosHoldLine', 'ModifierGroup', 'Modifier', 'ProductModifierGroup', 'Combo', 'ComboItem', 'MenuCategory', 'MenuItem', 'MenuItemModifierGroup', 'MenuProduct', 'MenuItemVariant', 'AccompanimentGroup', 'MenuItemAccompanimentGroup', 'AccompanimentOption', 'KitchenStation', 'KitchenTicket', 'LoyaltyProgram', 'LoyaltyLedger', 'StoreCredit', 'StoreCreditLedger', 'CustomerTab', 'CustomerTabLedger', 'MenuQrSession', 'OnlineOrder', 'PosTableZone', 'PosTable', 'PosTableOrder', 'PosTableReservation', 'Order', 'OrderItem', 'OrderItemModifier', 'PosRefund', 'PosApprovalGrant', 'SplitBill', 'SplitBillItem', 'StockPostingJob', 'InventoryException', 'PosReportSnapshot']);
const SYNC = new Set(['PosDevice', 'SyncOpDeadLetter']);
const PROCUREMENT = new Set(['PurchaseRequest', 'PurchaseRequestLine', 'PurchaseOrder', 'PurchaseOrderLine', 'PurchasePayment', 'GoodsReceiptNote', 'GoodsReceiptLine', 'LandedCost', 'LandedCostCharge', 'LandedCostAllocation', 'VendorBillReceiptMatch', 'VendorBillLink', 'ThreeWayMatch', 'DebitNote', 'DebitNoteLine']);
const MANUFACTURING = /^(Bom|BomLine|Production\w*|WorkCenter|Resource|Routing|RoutingOperation|WorkOrder)$/;

export function moduleOf(name) {
  if (KERNEL.has(name)) return 'kernel';
  if (ACCOUNTING.has(name) || /^Report\w+Snapshot$/.test(name)) return 'accounting';
  if (INVOICING.has(name)) return 'invoicing';
  if (POS.has(name)) return 'pos';
  if (SYNC.has(name)) return 'sync';
  if (PROCUREMENT.has(name)) return 'procurement';
  if (MANUFACTURING.test(name)) return 'manufacturing';
  if (/^Hr/.test(name)) return 'hr';
  if (/^Rental/.test(name)) return 'rental';
  if (/^Repair/.test(name)) return 'repair';
  if (/^Asset/.test(name)) return 'fixedasset';
  if (/^Bottle/.test(name)) return 'beverage';
  if (/^Task/.test(name)) return 'task';
  if (name === 'Deal' || name === 'Activity') return 'crm';
  if (/^Expense/.test(name)) return 'expenses';
  if (/^(Document|DMS|Template|OrganizationDocumentType)/.test(name)) return 'documents';
  if (/^(Communication|Conversation|Message|External|WhatsApp)/.test(name)) return 'communication';
  if (/^(Inventory|Stock|Waste)/.test(name)) return 'inventory';
  return 'core';
}

// ---------- parse ----------
const enums = {};
for (const m of schema.matchAll(/^enum (\w+) \{([^}]*)\}/gm)) {
  enums[m[1]] = m[2]
    .split('\n')
    .map((l) => l.replace(/\/\/.*/, '').trim())
    .filter(Boolean)
    .map((l) => l.split(/\s+/)[0]);
}
const models = {};
for (const m of schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
  const fields = [];
  for (const raw of m[2].split('\n')) {
    const line = raw.replace(/\/\/.*$/, '').trim();
    if (!line || line.startsWith('@@')) continue;
    const mm = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
    if (!mm) continue;
    const [, name, type, list, opt, attrs] = mm;
    fields.push({ name, type, list: !!list, optional: !!opt, attrs });
  }
  models[m[1]] = { name: m[1], fields, module: moduleOf(m[1]) };
}

// ---------- helpers ----------
const SCALARS = new Set(['String', 'Int', 'BigInt', 'Float', 'Decimal', 'Boolean', 'DateTime', 'Json', 'Bytes']);
const LIST_TYPES = { String: 'String', Int: 'Integer', BigInt: 'Long', Float: 'Double', Decimal: 'java.math.BigDecimal', Boolean: 'Boolean', DateTime: 'java.time.Instant' };
const javaField = (n) => (JAVA_KW.has(n) ? n + '_' : n);
const cap = (s) => s[0].toUpperCase() + s.slice(1);
function constName(v) {
  let c = v.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').toUpperCase();
  if (/^\d/.test(c)) c = '_' + c;
  return c;
}
// Enum lives in its only using module; enums used by several modules go to the open
// "shared" module (com.inventoryerp.shared.domain) so no module reaches into another.
const enumUsers = {};
for (const model of Object.values(models)) for (const f of model.fields) if (enums[f.type]) (enumUsers[f.type] ??= new Set()).add(model.module);
const enumModule = {};
for (const e of Object.keys(enums)) {
  const users = enumUsers[e] ?? new Set(['shared']);
  enumModule[e] = users.size === 1 ? [...users][0] : 'shared';
}

let skipped = 0;
function write(file, content) {
  if (fs.existsSync(file) && !fs.readFileSync(file, 'utf8').includes('@generated')) {
    skipped++;
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

// ---------- enums ----------
for (const [name, values] of Object.entries(enums)) {
  const pkg = `${BASE_PKG}.${enumModule[name]}.domain`;
  const consts = values.map((v) => [constName(v), v]);
  const seen = new Set();
  for (const [c] of consts) {
    if (seen.has(c)) throw new Error(`enum ${name}: constant clash ${c}`);
    seen.add(c);
  }
  write(
    path.join(outBase, enumModule[name], 'domain', `${name}.java`),
    `${MARK}
package ${pkg};

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonValue;
import com.inventoryerp.shared.persistence.DbEnum;
import com.inventoryerp.shared.persistence.DbEnumConverter;
import jakarta.persistence.Converter;

/** Postgres enum {@code "${name}"}. {@link #value()} is the exact DB and JSON value. */
public enum ${name} implements DbEnum {
${consts.map(([c, v]) => `    ${c}("${v}")`).join(',\n')};

    private final String value;

    ${name}(String value) {
        this.value = value;
    }

    @Override
    @JsonValue
    public String value() {
        return value;
    }

    @JsonCreator
    public static ${name} fromValue(String value) {
        return DbEnum.fromValue(${name}.class, value);
    }

    @Converter(autoApply = true)
    public static class JpaConverter extends DbEnumConverter<${name}> {
        public JpaConverter() {
            super(${name}.class);
        }
    }
}
`,
  );
}

// ---------- entities + repositories ----------
for (const model of Object.values(models)) {
  const pkg = `${BASE_PKG}.${model.module}.domain`;
  const imports = new Set([
    'jakarta.persistence.Column',
    'jakarta.persistence.Entity',
    'jakarta.persistence.Id',
    'jakarta.persistence.Table',
    'org.hibernate.annotations.DynamicInsert',
    'org.hibernate.annotations.DynamicUpdate',
  ]);
  const lines = [];
  const accessors = [];
  const scalarNames = new Set(model.fields.filter((f) => SCALARS.has(f.type) || enums[f.type]).map((f) => f.name));
  let hasUuidId = false;

  for (const f of model.fields) {
    const jf = javaField(f.name);
    const col = `@Column(name = "${f.name}"${f.optional || f.list ? '' : ', nullable = false'}`;
    const ann = [];
    let jtype;
    if (SCALARS.has(f.type) || enums[f.type]) {
      if (/@id\b/.test(f.attrs)) {
        ann.push('@Id');
        if (/autoincrement\(\)/.test(f.attrs)) {
          imports.add('jakarta.persistence.GeneratedValue');
          imports.add('jakarta.persistence.GenerationType');
          ann.push('@GeneratedValue(strategy = GenerationType.IDENTITY)');
        } else if (f.type === 'String') hasUuidId = true;
      }
      if (f.list) {
        imports.add('java.util.List');
        imports.add('org.hibernate.annotations.JdbcTypeCode');
        imports.add('org.hibernate.type.SqlTypes');
        jtype = enums[f.type] ? 'List<String>' : `List<${LIST_TYPES[f.type] ?? 'String'}>`;
        ann.push('@JdbcTypeCode(SqlTypes.ARRAY)', col + ')');
      } else if (enums[f.type]) {
        jtype = f.type;
        if (enumModule[f.type] !== model.module) imports.add(`${BASE_PKG}.${enumModule[f.type]}.domain.${f.type}`);
        ann.push(col + ')');
      } else {
        switch (f.type) {
          case 'String': jtype = 'String'; ann.push(col + ')'); break;
          case 'Int': jtype = 'Integer'; ann.push(col + ')'); break;
          case 'BigInt': jtype = 'Long'; ann.push(col + ')'); break;
          case 'Float': jtype = 'Double'; ann.push(col + ')'); break;
          case 'Boolean': jtype = 'Boolean'; ann.push(col + ')'); break;
          case 'Bytes': jtype = 'byte[]'; ann.push(col + ')'); break;
          case 'Json':
            jtype = 'String';
            imports.add('org.hibernate.annotations.JdbcTypeCode');
            imports.add('org.hibernate.type.SqlTypes');
            ann.push('@JdbcTypeCode(SqlTypes.JSON)', col + ')');
            break;
          case 'Decimal': {
            imports.add('java.math.BigDecimal');
            jtype = 'BigDecimal';
            const d = f.attrs.match(/@db\.Decimal\((\d+),\s*(\d+)\)/);
            ann.push(`${col}, precision = ${d ? d[1] : 65}, scale = ${d ? d[2] : 30})`);
            break;
          }
          case 'DateTime':
            if (/@db\.Date\b/.test(f.attrs)) {
              imports.add('java.time.LocalDate');
              jtype = 'LocalDate';
            } else {
              imports.add('java.time.Instant');
              jtype = 'Instant';
            }
            if (/@updatedAt/.test(f.attrs)) {
              imports.add('org.hibernate.annotations.UpdateTimestamp');
              ann.push('@UpdateTimestamp');
            } else if (f.name === 'createdAt' && /now\(\)/.test(f.attrs)) {
              imports.add('org.hibernate.annotations.CreationTimestamp');
              ann.push('@CreationTimestamp');
            }
            ann.push(col + ')');
            break;
        }
      }
      if (f.name === 'version' && OPTIMISTIC_LOCK.has(model.name)) {
        imports.add('jakarta.persistence.Version');
        ann.unshift('@Version');
      }
      lines.push(...ann.map((a) => '    ' + a), `    private ${jtype} ${jf};`, '');
      accessors.push([jtype, jf]);
      continue;
    }
    // Relation field: only same-module many-to-one navigations are generated.
    const target = models[f.type];
    if (!target || f.list) continue;
    const rel = f.attrs.match(/@relation\(([^)]*)\)/);
    const fk = rel && rel[1].match(/fields:\s*\[([^\]]+)\]/);
    if (!fk) continue;
    if (target.module !== model.module) continue;
    const fkCols = fk[1].split(',').map((s) => s.trim());
    const refs = (rel[1].match(/references:\s*\[([^\]]+)\]/)?.[1] ?? 'id').split(',').map((s) => s.trim());
    if (fkCols.length !== 1 || !scalarNames.has(fkCols[0])) continue;
    imports.add('jakarta.persistence.FetchType');
    imports.add('jakarta.persistence.JoinColumn');
    imports.add('jakarta.persistence.ManyToOne');
    const refCol = refs[0] === 'id' ? '' : `, referencedColumnName = "${refs[0]}"`;
    lines.push(
      '    @ManyToOne(fetch = FetchType.LAZY)',
      `    @JoinColumn(name = "${fkCols[0]}"${refCol}, insertable = false, updatable = false)`,
      `    private ${f.type} ${jf};`,
      '',
    );
    accessors.push([f.type, jf]);
  }
  const filters = [];
  if (ORG_SCOPED.has(model.name) && scalarNames.has('organizationId')) filters.push('TENANT');
  if (SOFT_DELETE.has(model.name) && scalarNames.has('deletedAt')) filters.push('SOFT_DELETE');
  if (filters.length) {
    imports.add('org.hibernate.annotations.Filter');
    imports.add(`${BASE_PKG}.shared.persistence.TenancyFilters`);
  }
  const filterAnn = filters
    .map((f) => `@Filter(name = TenancyFilters.${f}, condition = TenancyFilters.${f}_CONDITION, deduceAliasInjectionPoints = false)
`)
    .join('');
  if (hasUuidId) {
    imports.add('jakarta.persistence.PrePersist');
    imports.add('java.util.UUID');
  }

  const acc = accessors
    .map(([t, jf]) => {
      const p = cap(jf.replace(/_$/, ''));
      return `    public ${t} get${p}() {\n        return ${jf};\n    }\n\n    public void set${p}(${t} ${jf}) {\n        this.${jf} = ${jf};\n    }\n`;
    })
    .join('\n');
  const prePersist = hasUuidId
    ? `    @PrePersist
    void assignId() {
        if (id == null) {
            id = UUID.randomUUID().toString();
        }
    }

`
    : '';
  write(
    path.join(outBase, model.module, 'domain', `${model.name}.java`),
    `${MARK}
package ${pkg};

${[...imports].sort().map((i) => `import ${i};`).join('\n')}

/** Table {@code "${model.name}"} (owned by module {@code ${model.module}}). */
@Entity
@Table(name = "${model.name}")
@DynamicInsert
@DynamicUpdate
${filterAnn}public class ${model.name} {

${lines.join('\n')}${prePersist}${acc}}
`,
  );
  const idField = model.fields.find((f) => /@id\b/.test(f.attrs));
  const idType = idField?.type === 'BigInt' ? 'Long' : idField?.type === 'Int' ? 'Integer' : 'String';
  write(
    path.join(outBase, model.module, 'domain', `${model.name}Repository.java`),
    `${MARK}
package ${pkg};

import org.springframework.data.jpa.repository.JpaRepository;

public interface ${model.name}Repository extends JpaRepository<${model.name}, ${idType}> {}
`,
  );
}

const byModule = {};
for (const m of Object.values(models)) byModule[m.module] = (byModule[m.module] ?? 0) + 1;
console.log(`entities: ${Object.keys(models).length}, enums: ${Object.keys(enums).length}, hand-owned skipped: ${skipped}`);
console.log(JSON.stringify(byModule));
