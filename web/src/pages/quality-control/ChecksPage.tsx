import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { ClipboardCheck, Plus } from 'lucide-react';
import { PERMISSIONS } from '@erp/shared';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Textarea } from '@/components/ui/textarea';
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { DataTable, type Column } from '@/components/data-table';
import {
  DataTablePagination, FilterChips, FilterSelect, ListCard, ListPageHeader, ListToolbar, SearchInput, useListState,
  type ActiveChip,
} from '@/components/list';
import { SearchableSelect } from '@/components/ui/searchable-select';
import { useAuthStore } from '@/stores/auth.store';
import { notify, apiMessage } from '@/lib/notify';
import { dateTime } from '@/lib/format';
import { tx } from '@/lib/i18n/tx';
import {
  CHECK_STATUS_LABEL, CHECK_TYPE_LABEL, ORIGIN_LABEL, SOURCE_LABEL, useControlPoints, useCreateCheck, useQcChecks,
  useWorksheetTemplates, type QcCheck, type QcCheckStatus, type QcCheckType, type QcOrigin, type QcSourceType,
} from '@/features/quality-control/api';
import {
  BlocksPill, CheckStatusPill, Field, OptionalSelect, OriginPill, ProductPicker, StaffPicker, TeamPicker, Toggle,
} from './qc-ui';
import { optNum, toOptions } from './qc-format';

const FILTERS = { status: '', origin: '', checkType: '', sourceType: '' };

/** Quality checks (ADR-S087): generated by control points, raised by hand, or corrections. */
export function ChecksPage() {
  const navigate = useNavigate();
  const has = useAuthStore((s) => s.hasPermission);
  const list = useListState(FILTERS);
  const { status, origin, checkType, sourceType } = list.filters;
  const [creating, setCreating] = useState(false);
  const { data, isLoading, isFetching, isError } = useQcChecks({
    page: list.page, pageSize: list.pageSize, search: list.search || undefined, status: status || undefined,
    origin: origin || undefined, checkType: checkType || undefined, sourceType: sourceType || undefined,
  });
  const chips: ActiveChip[] = [
    ...(list.search ? [{ key: 'q', label: `“${list.search}”`, onRemove: () => list.setSearchInput('') }] : []),
    ...(status ? [{ key: 'status', label: CHECK_STATUS_LABEL[status as QcCheckStatus] ?? status, onRemove: () => list.setFilter('status', '') }] : []),
    ...(origin ? [{ key: 'origin', label: ORIGIN_LABEL[origin as QcOrigin] ?? origin, onRemove: () => list.setFilter('origin', '') }] : []),
    ...(checkType ? [{ key: 'type', label: CHECK_TYPE_LABEL[checkType as QcCheckType] ?? checkType, onRemove: () => list.setFilter('checkType', '') }] : []),
    ...(sourceType ? [{ key: 'source', label: SOURCE_LABEL[sourceType as QcSourceType] ?? sourceType, onRemove: () => list.setFilter('sourceType', '') }] : []),
  ];
  const columns: Column<QcCheck>[] = [
    { key: 'number', header: tx('Number'), render: (c) => <span className="font-medium text-primary">{c.checkNumber}</span> },
    { key: 'created', header: tx('Created'), render: (c) => <span className="whitespace-nowrap">{dateTime(c.createdAt)}</span> },
    { key: 'title', header: tx('Check'), render: (c) => <div><div className="line-clamp-1 max-w-[16rem]">{c.title}</div><div className="text-xs text-muted-foreground">{CHECK_TYPE_LABEL[c.checkType]}</div></div> },
    { key: 'product', header: tx('Product'), render: (c) => <div><div>{c.productName ?? '—'}</div><div className="text-xs text-muted-foreground">{c.batchNumber ?? ''}</div></div> },
    { key: 'source', header: tx('Source'), render: (c) => <div><div>{c.sourceRef ?? (c.sourceType === 'manual' ? '—' : SOURCE_LABEL[c.sourceType])}</div><div className="text-xs text-muted-foreground">{c.sourceType !== 'manual' ? SOURCE_LABEL[c.sourceType] : ''}</div></div> },
    { key: 'team', header: tx('Team'), render: (c) => c.teamName ?? '—' },
    { key: 'origin', header: tx('Origin'), render: (c) => <OriginPill origin={c.origin} /> },
    { key: 'status', header: tx('Status'), render: (c) => <div className="flex items-center gap-1.5"><CheckStatusPill status={c.status} /><BlocksPill blocks={c.blocksSource} /></div> },
  ];
  return (
    <div className="space-y-4">
      <ListPageHeader icon={ClipboardCheck} title={tx('Quality Checks')}
        description={tx('Checks generated by control points, manual checks and corrections, with every execution kept.')}
        actions={has(PERMISSIONS.qualityControl.check) && <Button onClick={() => setCreating(true)}><Plus className="mr-1.5 h-4 w-4" /> {tx('New check')}</Button>} />
      <ListToolbar chips={<FilterChips chips={chips} onClearAll={list.clearFilters} />}>
        <SearchInput value={list.searchInput} onChange={list.setSearchInput} placeholder={tx('Search number, title, batch, source…')} />
        <FilterSelect value={status} onChange={(v) => list.setFilter('status', v)} options={toOptions(CHECK_STATUS_LABEL)} allLabel={tx('All statuses')} />
        <FilterSelect value={checkType} onChange={(v) => list.setFilter('checkType', v)} options={toOptions(CHECK_TYPE_LABEL)} allLabel={tx('Any type')} />
        <FilterSelect value={origin} onChange={(v) => list.setFilter('origin', v)} options={toOptions(ORIGIN_LABEL)} allLabel={tx('Any origin')} />
        <FilterSelect value={sourceType} onChange={(v) => list.setFilter('sourceType', v)} options={toOptions(SOURCE_LABEL)} allLabel={tx('Any source')} />
      </ListToolbar>
      <ListCard>
        <div className={isFetching && !isLoading ? 'opacity-60 transition-opacity' : 'transition-opacity'}>
          <DataTable columns={columns} data={data?.data ?? []} loading={isLoading} getRowId={(c) => c.id}
            onRowClick={(c) => navigate(`/quality-control/checks/${c.id}`)} cellClassName="py-2.5 px-4" headerRowClassName="h-10"
            emptyMessage={isError ? tx('Could not load the checks.') : chips.length ? tx('No checks match these filters.') : tx('No quality checks yet.')} />
        </div>
        {data?.meta && (
          <DataTablePagination page={data.meta.page} pageSize={list.pageSize} total={data.meta.total} totalPages={data.meta.totalPages}
            onPageChange={list.setPage} onPageSizeChange={list.setPageSize} noun="check" />
        )}
      </ListCard>
      {creating && <ManualCheckDialog onClose={() => setCreating(false)} onSaved={(c) => navigate(`/quality-control/checks/${c.id}`)} />}
    </div>
  );
}

/** A manual check: from an active control point, or ad hoc. Manual checks never block an operation. */
export function ManualCheckDialog({ controlPointId: fixedPoint, onClose, onSaved }: {
  controlPointId?: string; onClose: () => void; onSaved?: (c: QcCheck) => void;
}) {
  const [pointId, setPointId] = useState(fixedPoint ?? '');
  const [checkType, setCheckType] = useState<QcCheckType>('pass_fail');
  const [title, setTitle] = useState('');
  const [productId, setProductId] = useState('');
  const [batchNumber, setBatchNumber] = useState('');
  const [sourceRef, setSourceRef] = useState('');
  const [teamId, setTeamId] = useState('');
  const [responsible, setResponsible] = useState('');
  const [instructions, setInstructions] = useState('');
  const [min, setMin] = useState('');
  const [max, setMax] = useState('');
  const [norm, setNorm] = useState('');
  const [unit, setUnit] = useState('');
  const [templateId, setTemplateId] = useState('');
  const [coveredQty, setCoveredQty] = useState('');
  const [includeInSpc, setIncludeInSpc] = useState(false);
  const points = useControlPoints({ page: 1, pageSize: 200, active: true });
  const templates = useWorksheetTemplates(true);
  const create = useCreateCheck();
  const submit = async () => {
    const adhoc = !pointId;
    try {
      const out = await create.mutateAsync({
        controlPointId: pointId || undefined, checkType: adhoc ? checkType : undefined, title: title.trim() || undefined,
        productId: productId || undefined, batchNumber: batchNumber.trim() || undefined, sourceRef: sourceRef.trim() || undefined,
        teamId: teamId || undefined, responsibleUserId: responsible || undefined, coveredQty: optNum(coveredQty),
        includeInSpc: pointId ? includeInSpc : undefined,
        ...(adhoc ? {
          instructions: instructions.trim() || undefined,
          ...(checkType === 'measure' ? { toleranceMin: optNum(min), toleranceMax: optNum(max), norm: optNum(norm), unit: unit.trim() || undefined } : {}),
          ...(checkType === 'worksheet' ? { worksheetTemplateId: templateId || undefined } : {}),
        } : {}),
      });
      notify.success(tx('Check {{number}} created', { number: out.checkNumber }));
      onSaved?.(out);
      onClose();
    } catch (err) {
      notify.error(apiMessage(err, tx('Could not create the check')));
    }
  };
  return (
    <Dialog open onOpenChange={(o) => !o && onClose()}>
      <DialogContent className="max-h-[90vh] overflow-y-auto sm:max-w-2xl">
        <DialogHeader>
          <DialogTitle>{tx('New quality check')}</DialogTitle>
          <DialogDescription>{tx('Manual checks are recorded for traceability and never block an operation.')}</DialogDescription>
        </DialogHeader>
        <div className="grid grid-cols-1 gap-3 sm:grid-cols-2">
          {!fixedPoint && (
            <Field label={tx('Control point')} className="sm:col-span-2">
              <SearchableSelect value={pointId} onValueChange={setPointId} placeholder={tx('None (ad-hoc check)')} searchPlaceholder={tx('Search control points…')}
                options={[{ value: '', label: tx('None (ad-hoc check)') }, ...(points.data?.data ?? []).map((p) => ({ value: p.id, label: p.title, code: p.reference }))]} />
            </Field>
          )}
          {!pointId && (
            <Field label={tx('Type')}><OptionalSelect value={checkType} onChange={(v) => setCheckType((v || 'pass_fail') as QcCheckType)} placeholder={tx('Type')} options={toOptions(CHECK_TYPE_LABEL)} /></Field>
          )}
          <Field label={tx('Title')} className={pointId ? 'sm:col-span-2' : ''}><Input value={title} onChange={(e) => setTitle(e.target.value)} placeholder={tx('Optional')} /></Field>
          <Field label={tx('Product')}><ProductPicker value={productId} onChange={setProductId} /></Field>
          <Field label={tx('Batch / lot')}><Input value={batchNumber} onChange={(e) => setBatchNumber(e.target.value)} /></Field>
          <Field label={tx('Reference')}><Input value={sourceRef} onChange={(e) => setSourceRef(e.target.value)} placeholder={tx('e.g. MO-00012, truck plate')} /></Field>
          <Field label={tx('Quantity covered')}><Input inputMode="decimal" value={coveredQty} onChange={(e) => setCoveredQty(e.target.value)} /></Field>
          <Field label={tx('Team')}><TeamPicker value={teamId} onChange={setTeamId} /></Field>
          <Field label={tx('Responsible')}><StaffPicker value={responsible} onChange={setResponsible} /></Field>
          {!pointId && checkType === 'measure' && (
            <>
              <Field label={tx('Minimum')}><Input inputMode="decimal" value={min} onChange={(e) => setMin(e.target.value)} /></Field>
              <Field label={tx('Maximum')}><Input inputMode="decimal" value={max} onChange={(e) => setMax(e.target.value)} /></Field>
              <Field label={tx('Norm')}><Input inputMode="decimal" value={norm} onChange={(e) => setNorm(e.target.value)} /></Field>
              <Field label={tx('Unit')}><Input value={unit} onChange={(e) => setUnit(e.target.value)} /></Field>
            </>
          )}
          {!pointId && checkType === 'worksheet' && (
            <Field label={tx('Worksheet template')} className="sm:col-span-2">
              <OptionalSelect value={templateId} onChange={setTemplateId} placeholder={tx('Choose a template')}
                options={(templates.data ?? []).map((t) => ({ value: t.id, label: `${t.name} (v${t.version})` }))} />
            </Field>
          )}
          {!pointId && (
            <Field label={tx('Instructions')} className="sm:col-span-2"><Textarea rows={3} value={instructions} onChange={(e) => setInstructions(e.target.value)} /></Field>
          )}
          {pointId && (
            <div className="sm:col-span-2"><Toggle checked={includeInSpc} onChange={setIncludeInSpc} label={tx('Include in statistics')} hint={tx('Manual checks are left out of control charts unless you include them.')} /></div>
          )}
        </div>
        <DialogFooter>
          <Button variant="outline" onClick={onClose}>{tx('Cancel')}</Button>
          <Button onClick={submit} disabled={create.isPending}>{tx('Create')}</Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
