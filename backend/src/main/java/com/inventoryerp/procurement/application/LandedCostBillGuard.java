package com.inventoryerp.procurement.application;

import static com.inventoryerp.procurement.application.ProcurementSql.org;

import com.inventoryerp.invoicing.application.VendorBillPostGuard;
import com.inventoryerp.kernel.crud.SqlRows;
import com.inventoryerp.kernel.settings.SettingResolverService;
import com.inventoryerp.kernel.settings.SettingResolverService.SettingContext;
import com.inventoryerp.shared.web.ApiException;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Component;

/**
 * One liability per supplier invoice between ordinary supplier bills and landed cost vouchers (readiness gap h-05 F1).
 * Always on, whatever the {@code bill.duplicateCheck} policy says: an ordinary bill cannot be posted for a supplier
 * invoice that a live voucher charge raises its own bill for ({@code billMode = generate}). The voucher side refuses the
 * opposite order ({@link LandedCostVoucherService}). Both sides take the same per-invoice advisory lock as the LC-2
 * duplicate registry, so the two checks cannot pass concurrently.
 */
@Component
class LandedCostBillGuard implements VendorBillPostGuard {

    /** Setting that chooses how supplier invoice numbers are compared (LC-2). */
    static final String NORMALIZATION = "procurement.invoiceRef.normalization";

    private final JdbcClient jdbc;
    private final SettingResolverService settings;

    LandedCostBillGuard(JdbcClient jdbc, SettingResolverService settings) {
        this.jdbc = jdbc;
        this.settings = settings;
    }

    /** The organisation's normalisation mode: {@code strict} (default) or {@code exact}. */
    String mode() {
        return settings.resolveString(NORMALIZATION, SettingContext.EMPTY);
    }

    /**
     * The supplier-invoice number as matched: upper case and trimmed; in {@code strict} mode (default) the separators
     * space - _ / . are removed too.
     */
    static String normalize(String ref, String mode) {
        if (ref == null || ref.isBlank()) {
            return null;
        }
        String v = ref.trim().toUpperCase(Locale.ROOT);
        return "exact".equals(mode) ? v : v.replaceAll("[ \\-_/.]", "");
    }

    /** {@link #normalize} as SQL over {@code column}. */
    static String sqlNormalized(String column, String mode) {
        String v = "upper(btrim(" + column + "))";
        return "exact".equals(mode) ? v : "regexp_replace(" + v + ", '[ ._/-]', '', 'g')";
    }

    /** Serialise everything that registers or bills one supplier invoice (same key as the LC-2 registry). */
    void lock(String supplierId, String norm) {
        jdbc.sql("SELECT pg_advisory_xact_lock(hashtext(?)::bigint)").param("lc-inv:" + org() + ":" + supplierId + ":"
                + norm).query().listOfRows();
    }

    /**
     * A posted or paid supplier bill entered outside landed cost (not generated by a voucher) for this supplier and
     * normalised invoice number, or null.
     */
    Map<String, Object> ordinaryBill(String supplierId, String norm) {
        String mode = mode();
        return SqlRows.one(jdbc.sql("SELECT id, \"documentNumber\", reference FROM \"Document\" WHERE"
                        + " \"organizationId\" = ? AND \"documentType\" = 'vendor_bill' AND \"partnerId\" = ? AND"
                        + " status::text IN ('posted', 'paid') AND coalesce(\"sourceType\", '') <> 'landed_cost' AND"
                        + " reference IS NOT NULL AND " + sqlNormalized("reference", mode) + " = ? ORDER BY"
                        + " \"issueDate\", id LIMIT 1")
                .params(org(), supplierId, norm));
    }

    @Override
    public List<String> beforePost(String billId, Map<String, Object> bill) {
        Map<String, Object> doc = SqlRows.one(jdbc.sql("SELECT \"partnerId\", reference, \"sourceType\" FROM \"Document\""
                + " WHERE id = ? AND \"organizationId\" = ?").params(billId, org()));
        if (doc == null || doc.get("partnerId") == null || "landed_cost".equals(doc.get("sourceType"))) {
            return List.of();
        }
        String ref = (String) doc.get("reference");
        String norm = normalize(ref, mode());
        if (norm == null) {
            return List.of();
        }
        String supplier = (String) doc.get("partnerId");
        lock(supplier, norm);
        Map<String, Object> charge = SqlRows.one(jdbc.sql("SELECT l.code, l.status, d.\"documentNumber\" FROM"
                        + " \"LandedCostCharge\" c JOIN \"LandedCost\" l ON l.id = c.\"landedCostId\" LEFT JOIN \"Document\" d"
                        + " ON d.id = c.\"vendorBillId\" WHERE c.\"organizationId\" = ? AND c.\"supplierId\" = ? AND"
                        + " c.\"supplierInvoiceRefNorm\" = ? AND c.live AND c.\"billMode\" = 'generate' AND (l.status IN"
                        + " ('draft', 'submitted', 'approved') OR (l.status = 'posted' AND d.id IS NOT NULL AND"
                        + " d.status::text <> 'cancelled')) ORDER BY l.\"createdAt\", l.id LIMIT 1")
                .params(org(), supplier, norm));
        if (charge == null) {
            return List.of();
        }
        if ("posted".equals(charge.get("status"))) {
            throw ApiException.conflict("Supplier invoice " + ref + " is already billed by landed cost "
                    + charge.get("code") + (charge.get("documentNumber") != null ? " (supplier bill "
                    + charge.get("documentNumber") + ")" : "") + "; cancel this bill instead of posting it");
        }
        throw ApiException.conflict("Supplier invoice " + ref + " is on landed cost " + charge.get("code")
                + ", which raises its own supplier bill; set that charge to link this bill, or remove it from the"
                + " voucher, before posting this bill");
    }
}
