    Report marginBands(Filter f) {
        String[][] bands = {{"loss", "Below 0 %"}, {"0-10", "0 – 10 %"}, {"10-20", "10 – 20 %"},
            {"20-30", "20 – 30 %"}, {"30-40", "30 – 40 %"}, {"40+", "40 % and above"}};
        Map<String, Map<String, Object>> rows = new LinkedHashMap<>();
        for (String[] b : bands) {
            rows.put(b[0], Obj.of("band", b[1], "products", 0, "revenue", 0, "cost", 0, "margin", 0));
        }
        for (Map<String, Object> p : facts.aggregate(f, Dim.PRODUCT)) {
            BigDecimal m = p.get("marginPercent") == null ? BigDecimal.ZERO : dec(p.get("marginPercent"));
            String k = m.signum() < 0 ? "loss" : m.compareTo(BigDecimal.TEN) < 0 ? "0-10"
                    : m.compareTo(BigDecimal.valueOf(20)) < 0 ? "10-20" : m.compareTo(BigDecimal.valueOf(30)) < 0
                            ? "20-30" : m.compareTo(BigDecimal.valueOf(40)) < 0 ? "30-40" : "40+";
            Map<String, Object> r = rows.get(k);
            r.put("products", ((Number) r.get("products")).intValue() + 1);
            for (String key : List.of("revenue", "cost", "margin")) {
                r.put(key, money(dec(r.get(key)).add(dec(p.get(key)))));
            }
        }
        List<Map<String, Object>> out = new ArrayList<>(rows.values());
        BigDecimal total = SalesReportKit.sum(out, "revenue");
        out.forEach(r -> {
            r.put("marginPercent", pct(dec(r.get("margin")), dec(r.get("revenue"))));
            r.put("share", pct(dec(r.get("revenue")), total));
        });
        Report rep = new Report().col("band", "Margin band", "text").col("products", "Products", "count")
                .col("revenue", "Net sales", "money").col("cost", "Cost of sales", "money")
                .col("margin", "Gross profit", "money").col("marginPercent", "Margin %", "percent")
                .col("share", "Revenue share %", "percent").rows(out)
                .sumTotals("products", "revenue", "cost", "margin");
        rep.total("band", "Total");
        rep.total("marginPercent", pct(dec(rep.totals.get("margin")), dec(rep.totals.get("revenue"))));
        Map<String, Object> t = facts.totals(f);
        SalesReportFacts.kpis(rep, t, true);
        rep.chart("bar", "band", bar("revenue", "Net sales"), bar("margin", "Gross profit"));
        costNote(rep, t);
        return rep;
    }

