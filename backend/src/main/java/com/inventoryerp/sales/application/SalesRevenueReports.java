    /** Last invoice date (up to {@code asOf}) per customer. */
    Map<String, Object> lastPurchase(List<String> partnerIds, LocalDate asOf) {
        Map<String, Object> out = new HashMap<>();
        if (partnerIds.isEmpty()) {
            return out;
        }
        List<Object> p = new ArrayList<>();
        p.add(org());
        p.add(asOf.plusDays(1));
        p.addAll(partnerIds);
        for (Map<String, Object> r : db.rows("SELECT \"partnerId\", max(\"issueDate\")::date AS d FROM \"Document\" WHERE"
                + " \"organizationId\" = ? AND \"documentType\" = 'sales_invoice' AND status IN ('posted', 'paid') AND"
                + " \"issueDate\" < ? AND \"partnerId\" IN (" + SalesDb.marks(partnerIds.size()) + ") GROUP BY 1", p)) {
            out.put(str(r.get("partnerId")), r.get("d"));
        }
        return out;
    }

    Report frequency(Filter f) {
        List<Map<String, Object>> rows = facts.aggregate(f, Dim.CUSTOMER);
        for (Map<String, Object> r : rows) {
            long docs = ((Number) r.get("documents")).longValue();
            Long span = SalesReportKit.daysBetween(r.get("firstDate"), r.get("lastDate"));
            r.put("avgDaysBetween", docs > 1 && span != null ? BigDecimal.valueOf(span)
                    .divide(BigDecimal.valueOf(docs - 1), 1, RoundingMode.HALF_UP) : null);
            long months = Math.max(1, java.time.temporal.ChronoUnit.MONTHS.between(f.from().withDayOfMonth(1),
                    f.to().withDayOfMonth(1)) + 1);
            r.put("perMonth", BigDecimal.valueOf(docs).divide(BigDecimal.valueOf(months), 2, RoundingMode.HALF_UP));
            r.put("daysSince", SalesReportKit.daysBetween(r.get("lastDate"), f.to()));
            SalesReportFacts.drillFor(r, Dim.CUSTOMER, str(r.get("k0")));
        }
        rows.sort(SalesReportKit.byDesc("documents"));
        Report rep = new Report().col("label", "Customer", "text").col("documents", "Invoices", "count")
                .col("firstDate", "First purchase", "date").col("lastDate", "Last purchase", "date")
                .col("avgDaysBetween", "Avg days between", "days").col("perMonth", "Purchases / month", "number")
                .col("aov", "Avg invoice value", "money").col("revenue", "Net sales", "money")
                .col("daysSince", "Days since last", "days").rows(rows).sumTotals("documents", "revenue");
        rep.total("label", "Total");
        List<BigDecimal> gaps = rows.stream().map(r -> r.get("avgDaysBetween")).filter(v -> v != null).map(SalesDb::dec)
                .toList();
        rep.kpi("customers", "Buying customers", rows.size(), "count")
                .kpi("repeat", "Repeat customers", rows.stream().filter(r -> ((Number) r.get("documents")).longValue() > 1)
                        .count(), "count")
                .kpi("gap", "Avg days between purchases", gaps.isEmpty() ? null : gaps.stream()
                        .reduce(BigDecimal.ZERO, BigDecimal::add).divide(BigDecimal.valueOf(gaps.size()), 1,
                                RoundingMode.HALF_UP), "days");
        rep.chart("hbar", "label", bar("documents", "Invoices")).chartData(rows.subList(0, Math.min(15, rows.size())));
        return rep;
    }

