    Report priceVariance(Filter f) {
        List<Map<String, Object>> rows = facts.aggregateWhere(f, " AND f.type = 'sales_invoice'", Dim.PRODUCT);
        Map<String, BigDecimal> list = new HashMap<>();
        List<String> ids = rows.stream().map(r -> str(r.get("k0"))).filter(i -> i != null).toList();
        if (!ids.isEmpty()) {
            List<Object> p = new ArrayList<>();
            p.add(org());
            p.addAll(ids);
            for (Map<String, Object> r : db.rows("SELECT id, \"salesPrice\" FROM \"Product\" WHERE \"organizationId\" = ?"
                    + " AND id IN (" + SalesDb.marks(ids.size()) + ")", p)) {
                list.put(str(r.get("id")), dec(r.get("salesPrice")));
            }
        }
        for (Map<String, Object> r : rows) {
            BigDecimal q = dec(r.get("quantity"));
            BigDecimal lp = list.getOrDefault(str(r.get("k0")), BigDecimal.ZERO);
            BigDecimal avg = q.signum() == 0 ? BigDecimal.ZERO : dec(r.get("revenue")).divide(q, 4, RoundingMode.HALF_UP);
            r.put("listPrice", money(lp));
            r.put("avgPrice", money(avg));
            r.put("variance", money(avg.subtract(lp)));
            r.put("variancePercent", pct(avg.subtract(lp), lp));
            r.put("impact", money(avg.subtract(lp).multiply(q)));
            SalesReportFacts.drillFor(r, Dim.PRODUCT, str(r.get("k0")));
        }
        rows.sort(SalesReportKit.byAsc("impact"));
        Report rep = new Report().col("label", "Product", "text").col("quantity", "Quantity", "qty")
                .col("listPrice", "List price", "money").col("avgPrice", "Avg selling price", "money")
                .col("variance", "Variance / unit", "money").col("variancePercent", "Variance %", "percent")
                .col("impact", "Revenue effect", "money").col("revenue", "Net sales", "money").rows(rows)
                .sumTotals("impact", "revenue");
        rep.total("label", "Total");
        rep.kpi("impact", "Revenue effect vs list", rep.totals.get("impact"), "money")
                .kpi("below", "Sold below list", rows.stream().filter(r -> dec(r.get("variance")).signum() < 0).count(),
                        "count");
        rep.chart("hbar", "label", bar("impact", "Revenue effect")).chartData(rows.subList(0, Math.min(15,
                rows.size())));
        rep.note("List price is the product's current sales price; selling price is net of discount and tax.");
        return rep;
    }
