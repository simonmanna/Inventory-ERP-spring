    Report ranking(Filter f, Dim dim) {
        String m = measure(f, "revenue");
        String sortKey = "quantity".equals(m) ? "baseQty" : m;
        List<Map<String, Object>> rows = facts.aggregate(f, dim);
        rows.sort(SalesReportKit.byDesc(sortKey));
        int limit = f.limit(10);
        BigDecimal total = SalesReportKit.sum(rows, sortKey);
        List<Map<String, Object>> top = new ArrayList<>(rows.subList(0, Math.min(limit, rows.size())));
        BigDecimal cum = BigDecimal.ZERO;
        int rank = 1;
        for (Map<String, Object> r : top) {
            r.put("rank", rank++);
            cum = cum.add(dec(r.get(sortKey)));
            r.put("share", pct(dec(r.get(sortKey)), total));
            r.put("cumulative", pct(cum, total));
            SalesReportFacts.drillFor(r, dim, str(r.get("k0")));
        }
        Report rep = new Report().col("rank", "#", "count").col("label", dim.title(), "text")
                .col("documents", "Invoices", "count").col("baseQty", "Quantity", "qty")
                .col("revenue", "Net sales", "money").col("margin", "Gross profit", "money")
                .col("marginPercent", "Margin %", "percent").col("share", "Share %", "percent")
                .col("cumulative", "Cumulative %", "percent").rows(top)
                .sumTotals("documents", "baseQty", "revenue", "margin");
        rep.total("label", "Top " + top.size());
        rep.kpi("count", "Ranked", rows.size(), "count")
                .kpi("topShare", "Top " + top.size() + " share", pct(cum, total), "percent")
                .kpi("leader", "Leader", top.isEmpty() ? null : top.getFirst().get(sortKey),
                        "quantity".equals(m) ? "qty" : "money", top.isEmpty() ? null : str(top.getFirst().get("label")));
        rep.chart("hbar", "label", bar(sortKey, "quantity".equals(m) ? "Quantity" : "margin".equals(m) ? "Gross profit"
                : "Net sales"));
        return rep;
    }

