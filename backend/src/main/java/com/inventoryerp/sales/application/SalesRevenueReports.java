    private static String measure(Filter f, String fallback) {
        String m = f.measure() == null ? fallback : f.measure();
        if (!Set.of("revenue", "quantity", "margin", "discount", "documents").contains(m)) {
            throw com.inventoryerp.shared.web.ApiException.badRequest(
                    "measure must be one of: revenue, quantity, margin, discount, documents");
        }
        return m;
    }

