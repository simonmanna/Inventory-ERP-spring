    Report discountImpact(Filter f, Dim dim) {
        List<Map<String, Object>> rows = facts.aggregate(f, dim);
        for (Map<String, Object> r : rows) {
            BigDecimal gross = dec(r.get("gross")).subtract(dec(r.get("returns")));
            BigDecimal cost = dec(r.get("cost"));
            BigDecimal before = gross.subtract(cost);
            r.put("listValue", money(gross));
            r.put("profitBefore", money(before));
            r.put("marginBefore", pct(before, gross));
            r.put("impact", money(dec(r.get("discount")).negate()));
            Object mb = pct(before, gross);
            Object ma = r.get("marginPercent");
            r.put("points", mb == null || ma == null ? null : num(dec(ma).subtract(dec(mb))));
            SalesReportFacts.drillFor(r, dim, str(r.get("k0")));
        }
        rows.sort(SalesReportKit.byDesc("discount"));
        Report rep = new Report().col("label", dim.title(), "text").col("listValue", "Sales before discount", "money")
                .col("discount", "Discounts", "money").col("cost", "Cost of sales", "money")
                .col("profitBefore", "Profit before discount", "money").col("margin", "Profit after discount", "money")
                .col("marginBefore", "Margin before %", "percent").col("marginPercent", "Margin after %", "percent")
                .col("points", "Margin points lost", "number").rows(rows)
                .sumTotals("listValue", "discount", "cost", "profitBefore", "margin");
        rep.total("label", "Total");
        BigDecimal pb = dec(rep.totals.get("profitBefore"));
        rep.kpi("discount", "Discounts", rep.totals.get("discount"), "money")
                .kpi("profitBefore", "Profit before discount", rep.totals.get("profitBefore"), "money")
                .kpi("margin", "Profit after discount", rep.totals.get("margin"), "money")
                .kpi("erosion", "Profit eroded by discounts", pct(dec(rep.totals.get("discount")), pb), "percent");
        rep.chart("bar", "label", bar("profitBefore", "Before discount"), bar("margin", "After discount"))
                .chartData(rows.subList(0, Math.min(15, rows.size())));
        return rep;
    }

    Report returnImpact(Filter f) {
        Bucket b = Bucket.of(f.groupBy(), Bucket.MONTH);
        Dim dim = Dim.valueOf(b.name());
        Map<String, Map<String, Object>> cn = new HashMap<>();
        facts.aggregateWhere(f, " AND f.type = 'credit_note'", dim).forEach(r -> cn.put(str(r.get("k0")), r));
        List<Map<String, Object>> rows = new ArrayList<>();
        for (Map<String, Object> s : SalesReportFacts.fill(facts.aggregate(f, dim), b, f.from(), f.to())) {
            Map<String, Object> c = cn.getOrDefault(str(s.get("k0")), Map.of());
            BigDecimal retRev = dec(c.get("revenue")).negate();
            BigDecimal retCost = dec(c.get("cost")).negate();
            BigDecimal gross = dec(s.get("gross"));
            Map<String, Object> r = Obj.of("label", s.get("label"), "gross", s.get("gross"), "returnedRevenue",
                    money(retRev), "returnedCost", money(retCost), "profitLost", money(retRev.subtract(retCost)),
                    "returnRate", pct(retRev, gross), "creditNotes", s.get("creditNotes"));
            r.put("revenue", s.get("revenue"));
            r.put("margin", s.get("margin"));
            rows.add(r);
        }
        Report rep = new Report().col("label", "Period", "text").col("gross", "Gross sales", "money")
                .col("creditNotes", "Credit notes", "count").col("returnedRevenue", "Revenue returned", "money")
                .col("returnedCost", "Cost returned", "money").col("profitLost", "Gross profit lost", "money")
                .col("returnRate", "Return rate %", "percent").col("revenue", "Net sales", "money")
                .col("margin", "Gross profit", "money").rows(rows)
                .sumTotals("gross", "creditNotes", "returnedRevenue", "returnedCost", "profitLost", "revenue",
                        "margin");
        rep.total("label", "Total");
        rep.total("returnRate", pct(dec(rep.totals.get("returnedRevenue")), dec(rep.totals.get("gross"))));
        rep.kpi("returned", "Revenue returned", rep.totals.get("returnedRevenue"), "money")
                .kpi("profitLost", "Gross profit lost", rep.totals.get("profitLost"), "money")
                .kpi("rate", "Return rate", rep.totals.get("returnRate"), "percent");
        rep.chart("combo", "label", bar("returnedRevenue", "Revenue returned"), line("returnRate", "Return rate %"));
        return rep;
    }

