package com.inventoryerp.biexport.application;

import java.time.Duration;
import java.util.LinkedHashMap;
import java.util.Map;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.boot.context.properties.bind.ConstructorBinding;

/**
 * Embedded Apache Superset dashboards ({@code app.bi.superset.*}, ADR-S078). Off unless {@code url} is set.
 *
 * @param url            base URL the API uses to reach Superset, e.g. {@code http://superset:8088}. Empty = disabled
 * @param publicUrl      base URL the browser loads the dashboard from (defaults to {@code url})
 * @param username       Superset service account that may create guest tokens (never logged)
 * @param password       its password (never logged)
 * @param dashboards     ERP module key ({@code sales}, {@code procurement}, ...) to the Superset embedded dashboard id
 * @param httpTimeout    how long to wait on Superset
 * @param dashboardsFile optional JSON file {@code {"dashboards": {module: id}}} written by
 *                       {@code tools/superset-provision --write-config}; ids set in {@code dashboards} win
 * @param secretsFile    optional env-style file ({@code SUPERSET_EMBED_USERNAME=...}) generated by the compose stack;
 *                       a username or password set directly wins
 */
@ConfigurationProperties("app.bi.superset")
public record SupersetProperties(
        String url,
        String publicUrl,
        String username,
        String password,
        Map<String, String> dashboards,
        Duration httpTimeout,
        String dashboardsFile,
        String secretsFile) {

    @ConstructorBinding
    public SupersetProperties {
        url = url == null ? "" : url.trim().replaceAll("/+$", "");
        publicUrl = publicUrl == null || publicUrl.isBlank() ? url : publicUrl.trim().replaceAll("/+$", "");
        username = username == null ? "" : username;
        password = password == null ? "" : password;
        Map<String, String> clean = new LinkedHashMap<>();
        if (dashboards != null) {
            dashboards.forEach((k, v) -> {
                if (v != null && !v.isBlank()) {
                    clean.put(k, v.trim());
                }
            });
        }
        dashboards = Map.copyOf(clean);
        httpTimeout = httpTimeout == null ? Duration.ofSeconds(10) : httpTimeout;
        dashboardsFile = dashboardsFile == null ? "" : dashboardsFile.trim();
        secretsFile = secretsFile == null ? "" : secretsFile.trim();
    }

    /** Settings without the optional files (tests, and a deployment that sets everything directly). */
    public SupersetProperties(String url, String publicUrl, String username, String password,
            Map<String, String> dashboards, Duration httpTimeout) {
        this(url, publicUrl, username, password, dashboards, httpTimeout, null, null);
    }

    /** Is Superset configured at all? */
    public boolean enabled() {
        return !url.isEmpty() && !username.isEmpty();
    }

    /**
     * These settings with the values read from the files filled in where nothing was set directly.
     *
     * @param fileUsername   the service account from the secrets file ("" = none)
     * @param filePassword   its password ("" = none)
     * @param fileDashboards module to dashboard id from the dashboards file
     */
    SupersetProperties withFileValues(String fileUsername, String filePassword, Map<String, String> fileDashboards) {
        Map<String, String> merged = new LinkedHashMap<>(fileDashboards);
        merged.putAll(dashboards);
        // Only a complete account set directly wins: .env.example names the user but leaves the password to the stack.
        boolean ownAccount = !username.isEmpty() && !password.isEmpty();
        return new SupersetProperties(url, publicUrl, ownAccount ? username : fileUsername,
                ownAccount ? password : filePassword, merged, httpTimeout, dashboardsFile, secretsFile);
    }

    /** Never print the password. */
    @Override
    public String toString() {
        return "SupersetProperties[url=" + url + ", publicUrl=" + publicUrl + ", dashboards=" + dashboards.keySet()
                + "]";
    }
}
