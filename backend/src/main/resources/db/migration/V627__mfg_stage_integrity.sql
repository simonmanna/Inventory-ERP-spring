-- Integrity fix 2026-11-24 (MS-6): a monotonic posting sequence. "Latest posting" (LIFO reversal, processing-job cost
-- link, cost absorption) was ordered by createdAt then code text, so two postings in the same millisecond, or stage
-- numbers past 9 ("S10" < "S9") and posting numbers past 999, picked the wrong one.
ALTER TABLE "ProductionStagePosting" ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;

-- Existing rows: by creation time, then the per-order posting number (the code's numeric suffix), then the code.
WITH ordered AS (
    SELECT id,
           row_number() OVER (ORDER BY "createdAt",
               coalesce(nullif(substring(code FROM '([0-9]+)$'), '')::BIGINT, 0), code, id) AS rn
    FROM "ProductionStagePosting"
)
UPDATE "ProductionStagePosting" p SET seq = o.rn FROM ordered o WHERE o.id = p.id;

DO $$
DECLARE
    next_seq BIGINT;
BEGIN
    SELECT coalesce(max(seq), 0) + 1 INTO next_seq FROM "ProductionStagePosting";
    EXECUTE format('ALTER TABLE "ProductionStagePosting" ALTER COLUMN seq RESTART WITH %s', next_seq);
END $$;

ALTER TABLE "ProductionStagePosting" ALTER COLUMN seq SET NOT NULL;
CREATE UNIQUE INDEX "ProductionStagePosting_seq_key" ON "ProductionStagePosting" (seq);
CREATE INDEX "ProductionStagePosting_org_order_seq_idx" ON "ProductionStagePosting" ("organizationId", "orderId", seq);

-- Integrity fix 2026-11-24 (MS-8): a failed QC lot can be scrapped from quarantine (posting kind qc_scrap, line role
-- qc_scrap: the held quantity issued as waste; no WIP effect).
ALTER TABLE "ProductionStagePosting" DROP CONSTRAINT IF EXISTS "ProductionStagePosting_kind_check";
ALTER TABLE "ProductionStagePosting" ADD CONSTRAINT "ProductionStagePosting_kind_check"
    CHECK (kind IN ('issue', 'output', 'conversion', 'qc_release', 'qc_scrap'));

ALTER TABLE "ProductionStagePostingLine" DROP CONSTRAINT IF EXISTS "ProductionStagePostingLine_role_check";
ALTER TABLE "ProductionStagePostingLine" ADD CONSTRAINT "ProductionStagePostingLine_role_check"
    CHECK (role IN ('material', 'intermediate_in', 'transfer_in', 'conversion', 'main_output', 'co_product',
                    'by_product', 'waste', 'abnormal_scrap', 'transfer_out', 'qc_release', 'qc_scrap'));
