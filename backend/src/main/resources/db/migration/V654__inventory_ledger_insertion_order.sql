-- Finance readiness audit, Wave B: a deterministic order for stock ledger rows.
--
-- Rows written in the same millisecond (for example the lot rows of one FEFO issue, which also share a ledger code)
-- tied on "createdAt" and were broken by a random UUID, so "return in issue order" could pick the wrong lot.
-- "seq" records insertion order; readers order by ("createdAt", seq). Existing rows are numbered in physical order.
ALTER TABLE "InventoryLedger" ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX "InventoryLedger_reference_seq_idx" ON "InventoryLedger" ("organizationId", "referenceType", "referenceId", seq);
